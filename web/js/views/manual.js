/** 매뉴얼 DOM. 블록 순서는 신호 흐름(계획 → 유도 → 제어 → 기체 → 피드백) 순. */
export function renderManual(box) {
  const sec = (title, ...kids) => el("section", { class: "man-sec" },
    el("h3", {}, title), ...kids);
  const para = (html) => { const p = el("p"); p.innerHTML = html; return p; };
  const list = (items) => el("ul", {}, items.map((t) => {
    const li = el("li"); li.innerHTML = t; return li;
  }));

  const stepOf = Object.fromEntries(DESIGN_ORDER.map((s) => [s.page, s]));

  box.append(
    el("div", { class: "manual" },
      el("h2", {}, "블록도 매뉴얼"),
      el("p", { class: "hint" },
        "각 블록이 무엇을 하고, 왜 있으며, 기체에 무엇을 하는지. ",
        "증상과 튜닝은 이 도구에서 실제로 관측된 것만 적었습니다 — 수치는 데모 기체 설계점 값입니다."),

      sec("먼저 알아야 할 것",
        el("div", { class: "man-bg" }, BACKGROUND.map((b) =>
          el("div", { class: "man-q" },
            el("h4", {}, b.q),
            b.a.map((t) => para(t)))))),

      ...BLOCK_DOCS.map((d) => {
        const step = stepOf[d.page];
        return el("section", { class: "man-blk", id: `man-${d.page}` },
          el("div", { class: "man-head" },
            step
              ? el("span", { class: "step-tag", style: `background:${step.color}` }, `설계 ${step.n}`)
              : el("span", { class: "step-tag", style: "background:#5f6b78" }, "지원"),
            el("h3", {}, d.title),
            el("span", { class: "man-role" }, d.role),
            el("button", { class: "man-go", onclick: () => { location.hash = `#blocks/${d.page}`; } },
              "블록도 열기 ▸")),
          el("div", { class: "man-body" },
            // 왼쪽 = 한 번 읽는 설명, 오른쪽 = 막혔을 때 되돌아오는 것
            el("div", { class: "man-col" },
              el("h5", {}, "무엇을 하나"), para(d.what),
              el("h5", {}, "왜 있나"), para(d.why),
              el("h5", {}, "기체에 무엇을 하나"), para(d.effect)),
            el("div", { class: "man-col" },
              d.tuning ? el("div", {}, el("h5", {}, "튜닝"), list(d.tuning)) : null,
              el("h5", {}, "흔한 증상과 대처"),
              el("dl", { class: "man-tr" }, d.trouble.flatMap(([sym, fix]) => {
                const dd = el("dd"); dd.innerHTML = fix;
                return [el("dt", {}, sym), dd];
              })))));
      }),

      sec("튜닝 순서 요약",
        para("막혔을 때 돌아올 자리입니다. <b>안쪽에서 바깥으로, 감쇠에서 적분으로.</b>"),
        el("ol", { class: "man-order" }, [
          "<b>기체를 먼저 안다</b> — 트림을 잡고 선형화해 고유치·마진을 본다. 여기가 안 되면 아래는 의미가 없다.",
          "<b>SCAS</b> — 축마다 k_rate(감쇠) → kp(속도) → ki(정상오차) 순. 세 축을 따로.",
          "<b>α 리미터</b> — 보호마진을 정하고, 리미터가 물린 상태에서도 SCAS가 안정한지 확인.",
          "<b>오토파일럿</b> — 속도 → 고도 → 헤딩 순. 명령필터로 급함을 깎고, 선회 FF로 커플링을 미리 보상.",
          "<b>게인 스케줄</b> — 설계점을 여러 개 잡고 그 <b>사이</b>에서 마진을 재확인. 상한을 반드시 둘 것.",
          "<b>비선형 검증</b> — 전체 미션으로. 직진이 아니라 <b>선회를 포함한</b> 미션으로 볼 것.",
        ].map((t) => { const li = el("li"); li.innerHTML = t; return li; })))));
}
