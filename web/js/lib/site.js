/** 시험장 제원 — 화면 여러 곳이 같은 수를 말하게 하는 한 자리.
 *
 * 고흥 활주로 좌표·방위·길이는 `data/geo/goheung-runway.json`(항공영상 측정 기록)이
 * 정본이고, 이 파일은 그 값을 화면이 쓸 수 있는 형태로 옮겨 둔 것이다. 브라우저는
 * 빌드 단계가 없어 JSON을 정적으로 읽어 올 수 없으므로 **옮겨 적는 것이 불가피**하고,
 * 대신 `site.test.js`가 두 파일을 대조해 어긋나면 빨개진다 — `data/geodesy-fixture.json`을
 * 엔진·웹 테스트가 함께 읽어 두 구현을 묶는 것과 같은 장치다.
 *
 * 같은 좌표가 `data/README.md`의 굽는 명령에도 있다(지형 팩의 원점). 그쪽도 테스트가
 * 본다 — **셋 중 하나만 고치면 막힌다.**
 *
 * ## 여기 두지 않는 것 — 접지 지점 산포
 *
 * 산포(기본 GNSS 대 RTK)는 시험장 제원이 아니라 **항법 등급 · 접근 프로파일 · 제어
 * 스케줄의 함수**다. 실제로 그것을 여기 옮겨 적었다가 곧바로 틀렸다: 병행 작업이
 * `fcl/demo.py`의 동압 스케줄 상한을 4.0 → 2.0으로 내리자 승강타 진동이 줄어 산포가
 * 통째로 달라졌고, 화면은 낡은 수로 계산한 배수를 소수 한 자리까지 말하고 있었다
 * (게다가 테스트가 그 낡은 값을 고정해 **참값을 넣으면 빨개지는** 상태였다).
 * 순항 고도를 300 → 200으로 바꾼 것만으로도 값이 움직인다.
 *
 * 그래서 화면은 산포의 **수치를 말하지 않는다**. 현재 값을 재는 곳은
 * `engine/claw/tests/test_landing.py` 하나이고, 화면은 아래 접지 창처럼 **스스로
 * 검산되는 양**만 말한다.
 */

/** 고흥 국가종합비행성능시험장. 원점은 활주로 **남단 임계**다 —
 *  활주로를 "원점에서 heading 방향 length 구간"으로 그리는 규약
 *  (views/renderer-three.js runwayMarks)과 기본 미션이 북향인 것이 함께 정한다. */
export const GOHEUNG = {
  originLatDeg: 34.601303,
  originLonDeg: 127.212067,
  runwayHeadingRad: 0.05964, // 진방위 3.417°
  runwayLengthM: 1205.0,
  // 접지에서 정지까지 (engine/claw/tests/test_landing.py, 실측 868.8 m).
  // 엔진의 허용대 rel=0.12는 측정 불확실도가 아니라 회귀가 안 깨지도록 넉넉히 잡은
  // 밴드다 — 넓다는 것이 값이 안정적이라는 뜻은 아니다. **민감도에 주의**: 접지 창은
  // 두 큰 수의 차라 미끄럼이 12% 움직이면 창은 31% 움직인다. 플레어 속도(80 m/s)나
  // 스키드 마찰이 바뀌면 이 수를 다시 재야 한다.
  rolloutM: 870,
};

/** 접지가 일어나도 활주로 안에 설 수 있는 구간 [m].
 *
 * 산포를 활주로 **전장**과 견주면 안 된다 — 시단에 닿아도 미끄럼만큼은 굴러가므로,
 * 실제로 허용되는 접지 지점의 폭은 그만큼 짧다. 활주로가 1,500 m에서 실측 1,205 m로
 * 줄었을 때 이 구별을 놓쳐 "산포가 겨우 들어간다"고 쓴 적이 있다(리뷰 지적).
 */
export function touchdownWindowM(site = GOHEUNG) {
  return site.runwayLengthM - site.rolloutM;
}
